import { Color } from './color.js';

/**
 * A CSS color name together with its color.
 *
 * @typedef {{name: string, color: Color}} NamedColor
 */

/**
 * Create a (frozen) table entry from integer RGB values.
 *
 * @param {string} name
 * @param {number} r
 * @param {number} g
 * @param {number} b
 * @returns {NamedColor}
 */
function namedColor(name, r, g, b) {
  return Object.freeze({
    name,
    color: Color.fromRgb(r, g, b),
  });
}

